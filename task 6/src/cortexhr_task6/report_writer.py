"""Task 6 - writes the Markdown comparison report. All figures come from `ctx`."""
from __future__ import annotations

from typing import Dict

import numpy as np
import pandas as pd

from .payroll_evaluation import ALL_ERRORS
from .reporting import TYPE_NOTES, hardest_types, md_table


def _get(df: pd.DataFrame, approach: str, error_type: str, col: str):
    row = df[(df["approach"] == approach) & (df["error_type"] == error_type)]
    return row.iloc[0][col]


def build_report(ctx: Dict) -> str:
    pt: pd.DataFrame = ctx["per_type"]
    ov: pd.DataFrame = ctx["overall"]
    overlap: pd.DataFrame = ctx["overlap"]
    clean: Dict = ctx["clean_overlap"]
    rule_hits: pd.DataFrame = ctx["rule_hits"]
    sens: pd.DataFrame = ctx["sensitivity"]
    diag: Dict = ctx["diagnostics"]
    j = ctx["join"]
    dq = ctx["data_quality"]
    mcfg, rcfg = ctx["model_config"], ctx["rule_config"]
    types = [t for t in pt["error_type"].unique() if t != ALL_ERRORS]
    A = ALL_ERRORS
    R, M, C = "Rules only", "Isolation Forest only", "Combined (rules OR model)"

    def o(app, col):
        return _get(pt, app, A, col)

    L = []
    w = L.append
    w("# Task 6 - Payroll Outlier Detector: Comparison Report\n")
    w("_Generated by `scripts/run_task6.py`. Every number below is computed from the run; none is typed by hand._\n")
    if not ctx["official_label_resource"]:
        w("> **PROVISIONAL RESULTS.** The required evaluation sheet `unlock_CX-06` was **not available** in the workbook. "
          f"`{ctx['label_sheet']}` was used as a substitute. The results below stay provisional until the internship team confirms the substitute is acceptable. "
          "No permission to use it has been assumed.\n")
    if ctx["original_mode"]:
        w("> **Mode: ORIGINAL EXPERIMENT settings** (file-order duplicate rule and file-order model fit, with a full-input-window role reference). Results depend on input row order. "
          "The corrected default is documented in the main report.\n")

    # ---------------- 1 dataset
    w("## 1. Dataset overview\n")
    w(f"- Workbook sheet `payroll_monthly_features`: **{dq['rows']:,} payslips**, {dq['employees']} employees, {dq['months']} monthly runs.")
    w(f"- Label source: sheet **`{ctx['label_sheet']}`** ({j['label_rows']} labelled payslips, {len(types)} error types).")
    if ctx["label_sheet"] != "unlock_CX-06":
        w("- **Substitute evaluation resource.** The workbook contains no `unlock_CX-06` sheet (sheets present with labels: `payroll_anomaly_labels`). "
          "Following Task 5's convention (which fell back from `unlock_CX-05` to `attendance_anomaly_labels`), evaluation uses `payroll_anomaly_labels`. "
          "**Results are provisional** until the internship team confirms this is acceptable. If an official `unlock_CX-06` sheet is added to the workbook, the loader will use it automatically.")
    w(f"- Data quality (label-free): {dq['missing_numeric_values']} missing and {dq['invalid_numeric_values']} non-numeric required values; "
      f"{dq['duplicate_item_ids']} duplicate `payroll_item_id`; {dq['rows_in_employee_month_duplicate_groups']} rows sit in repeated employee+month groups; "
      f"{dq['negative_net_rows']} negative-net and {dq['zero_net_rows']} zero-net rows.")
    w("- **Join validation** (labels -> features on `payroll_item_id`): "
      f"{j['label_rows']} label rows, {j['matched_rows']} matched, {j['unmatched_rows']} unmatched, "
      f"{j['duplicate_label_keys']} duplicate label keys, {j['duplicate_feature_keys']} duplicate feature keys, "
      f"{j['evaluation_rows_used']} rows used for evaluation (of {j['feature_rows']:,} payslips).")
    w("- Label structure: one label per payslip, so the error types are **mutually exclusive**; each is evaluated one-vs-clean (see section 6).\n")
    w("The full column list with meaning, type and usage is in `task6_data_dictionary.csv`. Identifiers (`payroll_item_id`, `run_id`, `employee_id`, `month`, `role_id`, `department_id`) "
      "are never model features; the `PI-D` prefix of `payroll_item_id` would reveal double payments and is therefore blocked.\n")

    # ---------------- 2 features
    w("## 2. Engineered ratio features\n")
    w(md_table(ctx["feature_defs"]))
    w("\nUndefined ratios (division by zero, missing history) are **NaN, not 0**. Employee history and the role-pay reference use only the previous calendar month; a missing month gives no reference.\n")

    # ---------------- 3 rules
    w("## 3. Business rules\n")
    w(md_table(ctx["rule_defs"]))
    w("\nThresholds come from the data dictionary / policy or label-free reference data and are **not tuned on the labels** "
      f"(overtime cap {rcfg.overtime_cap_hours:g} h, gross tolerance {rcfg.gross_tolerance}, role ratio {rcfg.role_ratio_limit}, "
      f"jump {rcfg.fixed_gross_jump_limit}, drop {rcfg.fixed_gross_drop_limit}). "
      "The *set of rules* was designed knowing the eight error-type names from the assignment, so rules-only results are optimistic compared with real payroll where error types are unknown in advance.\n")

    # ---------------- 4 model
    w("## 4. Isolation Forest configuration\n")
    w(f"- `scikit-learn` IsolationForest, `n_estimators={mcfg.n_estimators}`, `random_state={mcfg.random_state}`, `contamination={mcfg.contamination}`.")
    w("- Contamination 2.5% was fixed **before** seeing labels, to match the published `anomaly_baselines` payroll recipe so that features, not alert budget, explain differences. "
      f"The labelled error rate is {j['label_rows'] / j['feature_rows']:.2%}; that number was not used.")
    w(f"- Features used ({len(ctx['kept_features'])}): {', '.join('`' + f + '`' for f in ctx['kept_features'])}. Constant features dropped: {ctx['dropped_features'] or 'none'}.")
    w("- Missing ratios are median-imputed using the training median (documented neutral choice; rules cover those cases).")
    w("- `if_flag = 1` means \"statistically unusual\", not \"proven error\". `if_anomaly_score`: higher = more abnormal. A fixed `score_threshold` can replace the contamination cut-off.")
    w("- Training is unsupervised and transductive (fitted on the payroll rows it scores). **No labels are used anywhere in fitting, preprocessing or feature selection.**\n")

    # ---------------- 5 detectors
    w("## 5. Three detection approaches\n")
    w("1. **Rules only** - flagged if at least one rule fires.\n2. **Isolation Forest only** - flagged if `if_flag = 1`; no rule information.\n"
      "3. **Combined** - `combined_flag = rules_only_flag OR if_flag` (exactly; verified by `tests/test_detector.py`). Individual rule flags and the model flag are kept in every output.\n")

    # ---------------- 6 methodology
    w("## 6. Evaluation methodology\n")
    w("- Per error type T: actual cases = payslips labelled T. **TP** = flagged and labelled T; **FN** = labelled T, not flagged; "
      "**FP** = flagged payslips with **no** error label (false alarms); **TN** = unlabelled payslips that were not flagged.")
    w("- Flags that land on a payslip carrying a *different* error type are neither TP nor FP for T (counted in `flagged_on_other_error_types`). "
      "`precision_strict` instead counts them as errors.")
    w("- Because the detectors do not predict *which* error type, every type shares the same false-alarm count, so per-type precision is dominated by it. "
      "Rule-specific precision is in section 9 (`task6_rule_hits.csv`).")
    w("- Precision = TP/(TP+FP), Recall = TP/(TP+FN), F1 = 2PR/(P+R). Undefined values are **n/a**, never 0.")
    w("- `ALL_ERRORS` pools the types; its precision/recall use the same definitions as the `anomaly_baselines` sheet.\n")

    # ---------------- 7 results
    w("## 7. Results by error type\n")
    tbl = ctx["results_table"].copy()
    w(md_table(tbl))
    w("\nFull metrics (TP, FP, FN, TN, F1, support, strict precision) for every approach and type: `task6_metrics_per_type.csv`.\n")
    f1 = pt[pt["error_type"] == A][["approach", "predicted_positive", "tp", "fp", "fn", "tn", "precision", "recall", "f1"]].rename(columns={"predicted_positive": "flagged"})
    w("Pooled over all errors:\n")
    w(md_table(f1))
    w("")
    comb_vs_model = (f"Rules + model vs model alone: recall {o(C,'recall'):.3f} vs {o(M,'recall'):.3f} "
                     f"(+{o(C,'tp') - o(M,'tp')} true errors), precision {o(C,'precision'):.3f} vs {o(M,'precision'):.3f}.")
    w(f"**{comb_vs_model}**")
    w(f"The combined OR detector also trades precision for recall relative to rules alone: precision {o(C,'precision'):.3f} vs {o(R,'precision'):.3f}, "
      f"recall {o(C,'recall'):.3f} vs {o(R,'recall'):.3f}. The model adds {int(overlap.loc[overlap.error_type == A, 'caught_by_model_only'].iloc[0])} true errors "
      f"that rules missed and {clean['flagged_by_model_only']} false alarms.\n")

    ci_rows = []
    for t in types + [A]:
        r = {"error_type": t, "actual_cases": int(_get(pt, R, t, "actual_cases"))}
        for label, app in (("rules", R), ("model", M), ("combined", C)):
            row = pt[(pt["approach"] == app) & (pt["error_type"] == t)].iloc[0]
            r[f"{label} recall (95% CI)"] = f"{row['recall']:.2f} ({row['recall_ci95_low']:.2f}-{row['recall_ci95_high']:.2f})"
        ci_rows.append(r)
    w("**Uncertainty.** With only 5-15 cases per error type, each recall is an estimate with a wide 95% Wilson interval "
      "(e.g. 5 of 5 still allows a true recall well below 1):\n")
    w(md_table(pd.DataFrame(ci_rows)))
    w("\nPer-type precision intervals are in `task6_metrics_per_type.csv`. Differences between types, or between detectors on a single type, should not be over-interpreted.\n")

    t = ctx["tiers"]
    flags_total_combined = int(t.iloc[-1]["alerts"])
    w("**Operational trade-off.** Rules fire on a clear business definition (negative net, gross that does not add up, a repeated payslip), so their alerts are easy to explain and mostly right; "
      "they can only find error types somebody thought to write a rule for. The Isolation Forest can surface unusual payslips no rule describes, but most of its alerts are false alarms "
      f"({int(clean['flagged_by_model_only'])} of its alerts were on payslips with no error label, and it also flags legitimate bonus months). The OR-combination therefore buys recall with reviewer workload: "
      f"{int(flags_total_combined)} alerts to review in total versus {int(o(R, 'predicted_positive'))} for rules alone. "
      "A payroll team may prefer a review policy that treats the two kinds of alert differently. The following is an **experimental view only**; it does not replace any detector above and uses no new settings:\n")
    w(md_table(t))
    w("\nThe tiers add up to the combined detector exactly. Whether Tier 2 is worth a reviewer's time is a business decision that depends on review cost versus the cost of a missed error; these numbers come from synthetic labels and must not be read as production performance.\n")

    # ---------------- 8 baseline
    w("## 8. Comparison with `anomaly_baselines`\n")
    w("The sheet holds one payroll row: *Isolation Forest on ratios, 2.5% contamination* (features `gross_vs_fixed, ded_ratio, net_ratio, overtime_hours_paid, dup_flag, net_pay`). "
      "It evaluates the same 7,355 payslips against the same 100 injected errors with TP/flagged and TP/injected, so the **pooled** row is directly comparable. "
      "The sheet gives no per-type numbers, so per-type comparison uses a replica.\n")
    w(md_table(ctx["baseline_overall"]))
    w("\n" + ctx["baseline_note"] + "\n")
    rs = ctx["replica_seeds"]
    pub_tp = int(round(ctx["overall"].iloc[0]["tp"]))
    inside = rs["tp"].min() <= pub_tp <= rs["tp"].max()
    w(f"Seed check (`task6_baseline_replica_seeds.csv`): across seeds {int(rs['seed'].min())}-{int(rs['seed'].max())} the replica's true positives range from {int(rs['tp'].min())} to {int(rs['tp'].max())} "
      f"and its flagged count from {int(rs['flagged'].min())} to {int(rs['flagged'].max())}. The published TP of {pub_tp} "
      + ("falls inside that range, so the gap could be seed-level randomness; the exact published run still cannot be reproduced from the sheet's documentation alone.\n"
         if inside else
         "falls **outside** that range, so the replica does not reproduce the published row at any tested seed. The sheet does not document everything needed "
         "(for example the exact `dup_flag` definition or any other settings), so the published baseline is **not reproducible beyond the features and contamination it lists**. "
         "Use the published row for the pooled headline comparison and treat per-type baseline figures as approximate.\n"))
    w("Per-type **recall** (replica baseline vs this work; positive delta = improvement, negative = regression):\n")
    w(md_table(ctx["baseline_per_type"]))
    w("")
    reg = ctx["baseline_per_type"]
    worse = reg[(reg["delta_model_vs_baseline"] < 0) | (reg["delta_combined_vs_baseline"] < 0)]
    if len(worse):
        w("Regressions: " + "; ".join(f"{r.error_type} (model {r.delta_model_vs_baseline:+.3f}, combined {r.delta_combined_vs_baseline:+.3f})" for r in worse.itertuples()) + ".")
    else:
        w("No error type regressed in recall for the model or the combined detector relative to the replica baseline.")
    still = pt[(pt["approach"] == C) & (pt["error_type"] != A) & (pt["recall"] < 1)]
    if len(still):
        w("Types still not fully caught by the combined detector: " + ", ".join(f"{r.error_type} ({int(r.tp)}/{int(r.actual_cases)})" for r in still.itertuples()) + ".")
    w("")

    # ---------------- 9 rules vs model
    w("## 9. What the rules catch that the model misses\n")
    w(md_table(overlap))
    w(f"\nOn payslips with **no** label ({clean['clean_rows']:,} rows), false alarms: rules only {clean['flagged_by_rules_only']}, model only {clean['flagged_by_model_only']}, both {clean['flagged_by_both']}.\n")
    w("Rule-by-rule hits (a rule can fire on several types; `flags_on_clean_rows` are its false alarms):\n")
    w(md_table(rule_hits))
    w("\n**Why a transparent rule can catch what a statistical detector misses.** Isolation Forest only sees *unusual combinations of ratios*. A payslip that is an exact repeat of an ordinary payslip, "
      "or whose gross is 12% low, has ordinary-looking ratios, so nothing isolates it - but a rule that encodes a business fact (one payment per employee per month; gross = earned fixed + overtime + variable; "
      "net must not be negative) fires regardless of how common the amounts are. "
      f"Measured here: the model caught {int(_get(pt, M, 'DOUBLE_PAYMENT', 'tp')) if 'DOUBLE_PAYMENT' in types else 'n/a'} of {int(_get(pt, M, 'DOUBLE_PAYMENT', 'actual_cases')) if 'DOUBLE_PAYMENT' in types else 'n/a'} double payments and "
      f"{int(_get(pt, M, 'STALE_SALARY', 'tp')) if 'STALE_SALARY' in types else 'n/a'} of {int(_get(pt, M, 'STALE_SALARY', 'actual_cases')) if 'STALE_SALARY' in types else 'n/a'} stale-salary payslips.\n")
    w("Why each type behaves as it does:\n")
    for t in types:
        w(f"- **{t}** (rules recall {_get(pt, R, t, 'recall'):.3f}, model recall {_get(pt, M, t, 'recall'):.3f}): {TYPE_NOTES.get(t, '')}")
    w("")
    ex = ctx["examples"]
    w("Representative payslips caught by rules but not by the model (the two earliest per type by month; identifiers masked; labels shown only because this is the evaluation report):\n")
    w(md_table(ex[["record_ref", "month", "error_type_label", "gross_pay", "net_pay", "gross_vs_expected", "detection_reasons"]], digits=2))
    w("")

    # ---------------- 10 findings & surprises
    lo, hi = diag['stale_gross_vs_expected_min'], diag['stale_gross_vs_expected_max']
    stale_range = f"{lo:.2f}" if round(lo, 2) == round(hi, 2) else f"{lo:.2f}-{hi:.2f}"
    w("## 10. Findings that were not planned\n")
    w(f"- **Isolation Forest false alarms:** {diag['if_false_alarms']} unlabelled payslips; {diag['if_false_alarm_share_with_variable_pay']:.0%} of them carry variable pay (bonus/incentive) versus {diag['overall_share_with_variable_pay']:.0%} of all payslips - "
      "legitimate bonus months look unusual to a ratio-only model.")
    w("- **Duplicate rule:** the data has no payment or bank reference, so a flag means *possible* duplicate. By default every payslip in a group of same-employee, same-month, identical-amount payslips is flagged "
      "(the data cannot say which copy is the extra one). The labels mark only the injected copy, so the legitimate original counts as a false alarm in the evaluation although a reviewer would want to see both. "
      "See section 11 for how this differs from the original experiment.")
    w(f"- **`rule_salary_drop`:** {diag['salary_drop_flags']} flags, {diag['salary_drop_flags_labelled']} on labelled payslips; "
      f"{diag['salary_drop_flags_month_after_role_mismatch']} of them are the month directly after a ROLE_MISMATCH payslip. Full review in section 11.\n")

    # ---------------- 11 review after the original experiment
    w("## 11. Review after the original experiment\n")
    w("The first (original) experiment is frozen in `reports/original_experiment/`. A code review afterwards changed the implementation in two different ways. "
      "They are kept apart here because they have different standing.\n")
    w("### 11a. Corrections made for methodological reasons (not chosen from labels)\n")
    w("- **Duplicate rule depended on row order.** The original flagged the *later row in the file*, so shuffling the input changed which copy was flagged. It now flags the whole group by default (`duplicate_selection=\"all\"`); `later_by_item_id` is available but only valid if item ids follow processing order.")
    w("- **Isolation Forest depended on row order.** The forest was fitted on rows in file order, so a shuffled file gave different flags. Rows are now put in a canonical order (month, employee, feature values) before fitting.")
    w("- **'Previous month' meant 'previous row'.** History features now look up the same employee's payslip in the previous *calendar* month; a missing month gives no history. (The workbook has no such gaps, so this did not change any number here.)")
    w("- Tests now shuffle and reverse the input and require identical flags. The corrections were found by running a row-shuffle check, but their effect on the metrics was only measured afterwards; the table shows it.\n")
    v = ctx["variants"]
    show_v = v[v["approach"].isin(["rules", "combined", "model"])][["variant", "approach", "flagged", "tp", "fp", "fn", "tn", "precision", "recall", "f1"]]
    w("Before/after (overall, same 7,355 payslips and 100 labelled errors; the third variant is **post-evaluation and exploratory**):\n")
    w(md_table(show_v))
    w("")
    w("### 11b. `rule_salary_drop` review (post-evaluation analysis)\n")
    w("- **Condition:** `monthly_fixed_gross` < 0.99 x the same employee's `monthly_fixed_gross` in the previous calendar month. It uses only `employee_id`, `month` and `monthly_fixed_gross`; it does not depend on row order, and it gives no flag when the previous month is missing.")
    w("- **Business purpose:** an unexplained fall in fixed pay is a legitimate payroll control (cross-period consistency), different from the gross-reconciliation rule (consistency inside one payslip). "
      "It was written for stale salaries. In this dataset the stale-salary errors changed gross and net, not the fixed gross, so the rule has **no true positive** here - but that reflects how the errors were injected, not proof that the control is useless on real payroll.")
    w(f"- **Observed after seeing labels:** {diag['salary_drop_flags']} flags, {diag['salary_drop_flags_labelled']} on labelled payslips, {diag['salary_drop_flags_month_after_role_mismatch']} in the month right after a ROLE_MISMATCH payslip (the fixed gross returning to normal).")
    w("- **Hypothesis tested (not adopted):** suppress the drop alert when the previous month was flagged as a spike and this month returns to the pre-spike level (within 1%). "
      "Available as `RuleConfig(suppress_drop_after_flagged_spike=True)`, off by default.")
    w("- **Why it is not adopted:** the suppression is only safe if the earlier spike was itself an *error*. The dataset has no review outcome. If the earlier jump was a genuine large raise and payroll then reverts to the old salary, "
      "that is exactly a stale-salary error, and the suppression would hide it (demonstrated by a test). The 13 removed false alarms are therefore not enough justification, and the hypothesis could not be justified independently of the evaluation labels. "
      "**The original rule is unchanged.** A payroll owner could adopt the suppression if spikes are reviewed and closed before the next run.\n")
    d = ctx["drop_review"]
    w("Before/after for the exploratory change (**post-evaluation analysis, not an unbiased final evaluation**):\n")
    w(md_table(d))
    w("")

    # ---------------- 11 thinking question
    w("## 12. Which error type is hardest to catch? Why would a person find it easy?\n")
    hm = hardest_types(pt, M)
    hc = hardest_types(pt, C)
    w(f"**Hardest for the Isolation Forest alone (lowest recall, {hm['recall'].iloc[0]:.3f}):** " + ", ".join(f"{r.error_type} ({int(r.tp)}/{int(r.actual_cases)})" for r in hm.itertuples()) + ".")
    for r in hm.itertuples():
        w(f"- {r.error_type}: {TYPE_NOTES.get(r.error_type, '')}")
    low = pt[(pt["approach"] == M) & (pt["error_type"] != A) & (pt["recall"] < 0.25) & (~pt["error_type"].isin(set(hm["error_type"])))]
    if len(low):
        w("Other types the model also largely misses (recall below 0.25): " + ", ".join(f"{r.error_type} ({int(r.tp)}/{int(r.actual_cases)})" for r in low.itertuples()) + ".")
    rarest = pt[(pt["approach"] == M) & (pt["error_type"] != A)].sort_values("actual_cases").iloc[0]
    w("A person can apply a business fact that the ratios cannot express (see the notes above): notice the same payslip twice, or that a payslip does not add up. "
      + (f"Rarity is not the cause: the rarest type ({rarest.error_type}, {int(rarest.actual_cases)} cases) is "
         + ("not among the hardest for the model." if rarest.error_type not in set(hm["error_type"]) else "among the hardest for the model, so rarity may contribute.")) + "\n")
    w(f"**Hardest for the combined detector (lowest recall, {hc['recall'].iloc[0]:.3f}):** " + ", ".join(f"{r.error_type} ({int(r.tp)}/{int(r.actual_cases)})" for r in hc.itertuples()) + ".")
    miss = diag["missed_rows"]
    ot = miss[miss["label"] == "OVERTIME_SPIKE"]
    if len(ot):
        w(f"The missed overtime payslips paid {', '.join(f'{h:g}' for h in ot['overtime_hours_paid'])} hours; ordinary payslips with overtime have a median of {diag['clean_overtime_hours_median']:g} h and a maximum of {diag['clean_overtime_hours_max']:g} h, "
          f"and those employees' other months reach up to {', '.join(f'{h:g}' for h in ot['employee_other_months_max_ot_hours'])} h. "
          "So these two are **not obviously wrong from this data alone**; a person would also struggle unless they could see the approved timesheet - context that is missing from the dataset.")
    mf = miss[miss["label"] == "MISSED_DEDUCTION"]
    if len(mf):
        w(f"The missed PF case has no previous month for that employee (`prev_pf_employee` is empty), so 'PF was dropped' cannot be established; a person with the employee's contract/PF enrolment record could tell.")
    w("**Limitations of this answer:** sample sizes are small (5-15 cases per type, so one missed payslip moves recall by 7-20 points; see the 95% intervals in section 7), and the labels are synthetic injections.\n")

    # ---------------- 12 sensitivity
    w("## 13. Post-hoc sensitivity (reporting only - not used to choose any setting)\n")
    show = sens[sens["variant"].str.startswith(("contamination", "seed", "duplicate", "input")) & (sens["approach"].isin(["model", "rules", "combined"]))]
    w(md_table(show[["variant", "approach", "flagged", "tp", "fp", "fn", "tn", "precision", "recall", "f1"]]))
    abl = sens[sens["variant"] == "ablation: without rule_salary_drop"]
    w("\nAblation of `rule_salary_drop` (post-hoc): " + "; ".join(f"{r.approach} precision {r.precision:.3f}, recall {r.recall:.3f}" for r in abl.itertuples()) + ".")
    w("Full table including one-rule-at-a-time ablations: `task6_sensitivity.csv`.\n")

    # ---------------- 13 limitations
    w("## 14. Limitations and recommended next steps\n")
    w("- Labels are injected, synthetic errors with crisp signatures; real payroll errors are messier. Passing unit tests and good numbers here do not prove real-world performance.")
    w("- The rule set was designed with knowledge of the eight error types; thresholds were not tuned on labels, but rules-only results are still optimistic.")
    if not ctx["official_label_resource"]:
        w(f"- No `unlock_CX-06` sheet exists in the workbook; `{ctx['label_sheet']}` was used as a substitute. **All results are provisional** until the internship team confirms it is acceptable.")
    w("- The duplicate rule has no payment/bank reference to work with, so it can only say *possible* duplicate; flagging the whole group also flags the legitimate original.")
    w("- `rule_salary_drop` had no true positives here (see section 11b); it was kept unchanged and its suppression variant was documented as an unadopted hypothesis.")
    w("- Per-type results rest on 5-15 labelled cases each (see the confidence intervals in section 7).")
    w("- The corrected default role reference uses the previous calendar month only. The Isolation Forest itself is transductive: it is fitted and scored on the full 18-month batch, so these scores are not a prospective evaluation of a live monthly deployment.")
    w("- `--original-experiment` intentionally uses a full-window role reference to preserve the historical comparison; this legacy mode is not the corrected default.")
    w("- The baseline recipe is not fully specified, so the replica only approximates the published figures (section 8).")
    w("- Next steps: add payment/bank references for duplicates; add a per-employee overtime history feature; have a payroll owner review thresholds and decide on `rule_salary_drop`; validate on a later, unseen period; consider a priority score to reduce the OR-combination's false-alarm load.\n")
    return "\n".join(L)
